const digest = (bytes) => createHash('sha256').update(bytes).digest('hex');
const sourceMismatch = sourceFiles.filter((file) => {
  const original = frontendBuildFiles.includes(file) ? path.join(path.dirname(desktop), 'frontend', 'dist', file.slice('runtime/frontend/'.length)) : file.startsWith('runtime/') ? path.join(path.dirname(desktop), file.slice('runtime/'.length)) : path.join(desktop, file);
  return !entries.includes(file) || digest(extractFile(archive, path.normalize(file))) !== digest(fs.readFileSync(original));
});
const version = JSON.parse(extractFile(archive, 'package.json')).version;
const extensionVersion = JSON.parse(extractFile(archive, path.normalize('runtime/browser-extension/temu-deep-collector/manifest.json'))).version;
const report = { ok: forbidden.length === 0 && missing.length === 0 && sourceMismatch.length === 0 && version === require('../package.json').version && hasNativeSqlite && hasSharp, version, extensionVersion, fileCount: entries.length, frontendBuildFileCount: frontendBuildFiles.length, forbidden, missing, sourceMismatch, hasNativeSqlite, hasSharp };
console.log(JSON.stringify(report, null, 2));
if (!report.ok) process.exitCode = 1;
